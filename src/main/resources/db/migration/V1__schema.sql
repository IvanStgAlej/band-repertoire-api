CREATE TABLE ensemble (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    type VARCHAR(20)  NOT NULL,
    city VARCHAR(120)
);

CREATE TABLE musician (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(120) NOT NULL,
    email           VARCHAR(180) NOT NULL,
    main_instrument VARCHAR(60)  NOT NULL,
    CONSTRAINT uq_musician_email UNIQUE (email)
);

CREATE TABLE membership (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ensemble_id BIGINT      NOT NULL REFERENCES ensemble (id) ON DELETE CASCADE,
    musician_id BIGINT      NOT NULL REFERENCES musician (id) ON DELETE CASCADE,
    instrument  VARCHAR(60) NOT NULL,
    joined_on   DATE        NOT NULL,
    CONSTRAINT uq_membership UNIQUE (ensemble_id, musician_id)
);

CREATE TABLE piece (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ensemble_id      BIGINT       NOT NULL REFERENCES ensemble (id) ON DELETE CASCADE,
    title            VARCHAR(200) NOT NULL,
    composer         VARCHAR(120),
    arranger         VARCHAR(120),
    duration_seconds INT          NOT NULL CHECK (duration_seconds > 0),
    difficulty       INT          NOT NULL CHECK (difficulty BETWEEN 1 AND 5),
    genre            VARCHAR(60)
);

CREATE TABLE rehearsal (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ensemble_id BIGINT    NOT NULL REFERENCES ensemble (id) ON DELETE CASCADE,
    starts_at   TIMESTAMP NOT NULL,
    location    VARCHAR(160),
    notes       VARCHAR(1000)
);

CREATE TABLE rehearsal_piece (
    rehearsal_id BIGINT NOT NULL REFERENCES rehearsal (id) ON DELETE CASCADE,
    piece_id     BIGINT NOT NULL REFERENCES piece (id) ON DELETE CASCADE,
    PRIMARY KEY (rehearsal_id, piece_id)
);

CREATE TABLE attendance (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rehearsal_id BIGINT  NOT NULL REFERENCES rehearsal (id) ON DELETE CASCADE,
    musician_id  BIGINT  NOT NULL REFERENCES musician (id) ON DELETE CASCADE,
    attended     BOOLEAN NOT NULL,
    reason       VARCHAR(200),
    CONSTRAINT uq_attendance UNIQUE (rehearsal_id, musician_id)
);

CREATE TABLE concert (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ensemble_id  BIGINT       NOT NULL REFERENCES ensemble (id) ON DELETE CASCADE,
    title        VARCHAR(160) NOT NULL,
    concert_date DATE         NOT NULL,
    venue        VARCHAR(160)
);

-- piece_id has no ON DELETE action: deleting a piece that is in a program must fail (the service answers 409 first),
-- while deleting an ensemble still works because the concert cascade removes the items in the same statement.
CREATE TABLE program_item (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concert_id BIGINT NOT NULL REFERENCES concert (id) ON DELETE CASCADE,
    piece_id   BIGINT NOT NULL REFERENCES piece (id),
    sort_order INT    NOT NULL,
    CONSTRAINT uq_program_piece UNIQUE (concert_id, piece_id),
    CONSTRAINT uq_program_order UNIQUE (concert_id, sort_order)
);
